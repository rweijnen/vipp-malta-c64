# --- 64tass ----------------------------------------------------------------------------
def emit():
    out = ["; generated by tools/im/gen_mission.py from tools/im/mission_script.py - do not edit\n"]
    for c in SCRIPT:
        op = c[0]
        if op == "LABEL":
            out.append(f"{c[1]}\n")
        elif op == "SCENE":
            pos = "$ff" if c[2] is None else str(c[2])
            out.append(f"            .byte C_SCENE, {c[1]}, {pos}\n            .word {c[3]}\n            .byte {c[4]}, {c[5]}\n")
        elif op == "ROOM":
            out.append(f"            .byte C_ROOM, {c[1]}\n            .word {c[2]}\n            .byte floor_y({c[3]}), {c[4]}\n")
        elif op in ("RUN",):
            out.append(f"            .byte C_RUN\n            .word {c[1]}\n")
        elif op in ("GOTO", "ONDEATH"):
            out.append(f"            .byte C_{op}\n            .word {c[1]}\n")
        elif op in ("FLIP", "BACK"):
            out.append(f"            .byte C_{op}\n")
        elif op == "FACE":
            out.append(f"            .byte C_FACE, {c[1]}\n")
        elif op == "SEARCH":
            out.append(f"            .byte C_SEARCH, {c[1]}, {c[2]}\n")
        elif op in ("STAND", "SAY", "TERM", "RIDE"):
            out.append(f"            .byte C_{op}, {c[1]}\n")
        else:
            sys.exit(f"mission script: unknown command {c}")
    return "".join(out)


# --- simulation (mirrors src/mission.asm, mission_rooms.asm, mission_danger.asm) ---------
ROBOT_PAUSE, ZAP_TICKS, ZAP_COOL, ZAP_RANGE = 8, 16, 30, 56
RESULT_TICKS = 30
FLIP_DX, RUN_PX = 76, 5


class Robot:
    def __init__(self, x, y, lo, hi, typ):
        # robots_init
        self.x, self.y, self.lo, self.hi = x, y, lo, hi
        self.speed = (typ & 1) + 1
        self.frame = 6 if typ & 2 else 0
        self.state = 0                  # 0 walk, 1 wait, 2 turn, 3 fire
        self.timer = 0
        self.target = 0
        self.cool = 0


class Sim:
    def __init__(self, rooms, agent):
        self.rooms = rooms              # per room: list of (x, y, lo, hi, type)
        self.dx3, self.dy3 = agent      # signed per frame
        self.labels = {c[1]: i for i, c in enumerate(SCRIPT) if c[0] == "LABEL"}

    def robots_init(self):
        self.rob = [Robot(*r) for r in self.rooms[self.room]]

    def robots_tick(self):
        for r in reversed(self.rob):
            if r.state == 3:
                continue
            if r.state == 2:
                if r.frame == r.target:
                    r.state = 0
                elif r.frame > r.target:
                    r.frame -= 1
                else:
                    r.frame += 1
            elif r.state == 1:
                r.timer -= 1
                if r.timer == 0:
                    r.state = 2
                    r.target = 0 if r.frame else 6
            else:
                if r.frame == 0:
                    r.x += r.speed
                    if r.x > r.hi:
                        r.x, r.state, r.timer = r.hi, 1, ROBOT_PAUSE
                else:
                    r.x -= r.speed
                    if r.x < r.lo:
                        r.x, r.state, r.timer = r.lo, 1, ROBOT_PAUSE

    def zap_tick(self):
        for r in self.rob:
            if r.cool:
                r.cool -= 1
        if self.zap is not None:
            r = self.rob[self.zap]
            r.timer -= 1
            if r.timer == 0:
                r.state, r.cool, self.zap = 0, ZAP_COOL, None
            return
        for k in reversed(range(len(self.rob))):
            r = self.rob[k]
            if r.state >= 2 or r.cool or (r.y - 21) & 0xff != self.y:
                continue
            dx = self.x - r.x
            if dx >= 0:
                ok = r.frame == 0 and dx < ZAP_RANGE
            else:
                ok = r.frame == 6 and dx >= -ZAP_RANGE
            if ok:
                self.zap, r.state, r.timer = k, 3, ZAP_TICKS
                return

    def agent_box(self):
        f = self.frame
        if f < 16:
            return self.x + 6, self.x + 15, self.y + 2, self.y + 41
        dx = self.dx3[f] * (1 if self.face > 0 else -1)
        l0, t0 = self.x + dx, self.y + self.dy3[f]
        return l0 + 5, l0 + 16, t0 + 4, t0 + 18

    def hit(self):
        al, ar, at, ab = self.agent_box()

        def over(l, r, t, b):
            return ab >= t and b >= at and r >= al and ar >= l
        if self.zap is not None:
            r = self.rob[self.zap]
            l = r.x + 4 if r.frame == 0 else r.x - 28
            if over(l, l + 47, r.y + 5, r.y + 15):
                return f"zap of robot {self.zap}"
        for k in reversed(range(len(self.rob))):
            r = self.rob[k]
            if over(r.x + 4, r.x + 19, r.y, r.y + 20):
                return f"robot {k}"
        return None

    # script (script_next / script_tick / run_step)
    def start(self):
        while True:
            c = SCRIPT[self.pc]
            op = c[0]
            self.cmd = op
            if op == "LABEL":
                self.pc += 1
            elif op == "ONDEATH":
                self.death_go = self.labels[c[1]]
                self.pc += 1
            elif op == "FACE":
                self.face = 1 if c[1] == R else -1
                self.pc += 1
            elif op == "ROOM":
                _, self.room, self.x, row, face = c
                self.y, self.face, self.frame = 8 * row + 10, (1 if face == R else -1), 14
                self.entry = (self.x, self.y, self.face)
                self.scene = "room"
                self.zap = None
                self.robots_init()
                self.pc += 1
            elif op == "TERM":
                self.scene = "term"
                self.pc += 1
            elif op == "BACK":
                self.scene = "room"
                self.zap = None                       # danger_room
                for r in self.rob:
                    r.cool = 0
                    if r.state == 3:
                        r.state = 0
                self.pc += 1
            elif op == "STAND":
                self.wait, self.frame = c[1], 14
                self.pc += 1
                return
            elif op == "RUN":
                self.frame = 13
                return self.run_step()
            elif op == "FLIP":
                self.frame = 27
                self.pc += 1
                return
            elif op == "SEARCH":                      # the bar, then the result
                self.left, self.frame = c[1] + RESULT_TICKS, 15
                self.pc += 1
                return
            else:                                     # leaving the room
                return "out"

    def run_step(self):
        self.x += RUN_PX * self.face
        target = SCRIPT[self.pc][1]
        # (left: a negative X counts as there, as in run_step)
        if (self.face > 0 and self.x >= target) or (self.face < 0 and (self.x < 0 or target >= self.x)):
            self.pc += 1
            return self.start()

    def tick(self):
        op = self.cmd
        r = None
        if op == "RUN":
            self.frame = 13 if self.frame == 0 else self.frame - 1
            r = self.run_step()
        elif op == "FLIP":
            if self.frame == 16:
                self.x += FLIP_DX * self.face
                r = self.start()
            else:
                self.frame -= 1
        elif op == "SEARCH":
            self.left -= 1
            if self.left == 0:
                self.frame = 14
                r = self.start()
        elif op == "STAND":
            self.wait -= 1
            if self.wait == 0:
                r = self.start()
        return r

    def room_segment(self, pc, log):
        """From a ROOM command until the agent leaves; returns (deaths, causes, end pc)."""
        self.pc = pc
        self.face = 1
        deaths = []
        # C_ROOM runs inside the tick in which the command before it ends,
        # and the robots already move in that same tick (irq_main)
        first = self.start()
        t = 0
        while t < 5000:
            if t > 0:
                first = self.tick()
            t += 1
            if first == "out":
                return deaths, self.pc
            if self.scene != "room":
                continue
            self.robots_tick()
            self.zap_tick()
            why = self.hit()
            if why:
                deaths.append((t, self.x, why))
                log(f"    tick {t}: DEATH at x {self.x} frame {self.frame} ({why})")
                # death_frame: back at the door, robots at their places
                self.x, self.y, self.face = self.entry
                self.frame, self.zap = 14, None
                self.robots_init()
                self.pc = self.death_go
                if self.start() == "out":
                    return deaths, self.pc
        sys.exit("mission script: a room segment does not end")


def check(rooms, agent, verbose=False):
    """Simulate every room segment of one loop; returns the deaths."""
    sim = Sim(rooms, agent)
    deaths = []
    log = print if verbose else (lambda s: None)
    for i, c in enumerate(SCRIPT):
        if c[0] == "ROOM":
            log(f"room index {c[1]}:")
            d, _ = sim.room_segment(i, log)
            deaths += [(c[1],) + x for x in d]
    return deaths
