"""The security terminal screen of the original Impossible Mission, from a
VICE snapshot taken while a terminal is shown (record one with
tools/vicerecord.py while playing your own copy).

The terminal (as traced): no raster split; screen $4000, the lift charset
($4800, letters A-Z = $71-$8a, digits = $8b-$94), border 0, background 9,
multicolours 15 / 12; text in colour 7 (hires) on rows 3-17, columns 6-33,
inside a monitor drawn with characters plus 8 hires sprites for the bezel
corners (colour 15).

usage: extract_terminal.py TERMINAL_SNAPSHOT.vsf [--out assets/im]
writes terminal_screen.bin (1000 chars, the text area emptied),
       terminal_colram.bin (1000), terminal_sprites.bin (the corner sprite
       blocks), terminal.inc (colours, sprite positions, pointers)
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from vicesession import Vice  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent.parent
SPACE = 0x53
TEXT_ROWS = range(3, 18)
TEXT_COLS = range(6, 34)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("snapshot")
    ap.add_argument("--out", default=str(ROOT / "assets" / "im"))
    a = ap.parse_args()
    out = Path(a.out)
    with Vice(None) as v:
        v.cmd("r")
        v.cmd(f'undump "{Path(a.snapshot).resolve().as_posix()}"')
        vic = v.peek(0xd000, 0xd02e)
        if v.peek(0xdd00)[0] & 3 != 2 or vic[0x18] & 0xfe != 0x02:
            sys.exit("not a terminal snapshot: expected VIC bank 1, screen $4000, charset $4800")
        scr = v.peek(0x4000, 0x43e7)
        col = [c & 15 for c in v.peek(0xd800, 0xdbe7)]
        title = bytes(scr[3 * 40 + 6:3 * 40 + 34])
        if title[:3] != bytes([0x95, 0x95, 0x95]):
            sys.exit("not a terminal snapshot: row 3 does not start with ***")
        ptrs = v.peek(0x43f8, 0x43ff)
        blocks = sorted(set(ptrs))
        spr = b"".join(bytes(v.peek(0x4000 + b * 64, 0x4000 + b * 64 + 63)) for b in blocks)
    for r in TEXT_ROWS:
        for c in TEXT_COLS:
            scr[r * 40 + c] = SPACE
    (out / "terminal_screen.bin").write_bytes(bytes(scr))
    (out / "terminal_colram.bin").write_bytes(bytes(col))
    (out / "terminal_sprites.bin").write_bytes(spr)
    xs = [vic[2 * i] | (0x100 if vic[0x10] & (1 << i) else 0) for i in range(8)]
    ys = [vic[2 * i + 1] for i in range(8)]
    (out / "terminal.inc").write_text(
        "; generated by tools/im/extract_terminal.py - do not edit\n"
        f"TERM_BORDER = {vic[0x20] & 15}\nTERM_BG = {vic[0x21] & 15}\n"
        f"TERM_MC1 = {vic[0x22] & 15}\nTERM_MC2 = {vic[0x23] & 15}\n"
        f"TERM_TEXT = {col[3 * 40 + 6]}\n"
        f"TERM_SPR_COL = {vic[0x27] & 15}\n"
        "term_spr_x   .word " + ", ".join(str(x) for x in xs) + "\n"
        "term_spr_y   .byte " + ", ".join(str(y) for y in ys) + "\n"
        "term_spr_blk .byte " + ", ".join(str(blocks.index(p)) for p in ptrs) + "   ; index into terminal_sprites.bin\n")
    print(f"terminal: frame, colours, {len(blocks)} corner sprite blocks")


if __name__ == "__main__":
    main()
