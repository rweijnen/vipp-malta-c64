"""Tables for the VIPP Mission (src/mission.asm) from the extracted Impossible
Mission data in assets/im (see extract.py): writes build/mission_agent.inc.

Agent frames: per hires sprite piece (sprite 1 white overlay, 2 body, 3 legs)
the block number (0-63 within the agent sprites, $ff = piece not shown) and
its offset from the agent origin. Offsets are signed: dx is negated when the
agent faces left (as the original does with its delta tables).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
IM = ROOT / "assets" / "im"
OUT = ROOT / "build" / "mission_agent.inc"


def main():
    src = IM / "agent.json"
    if not src.exists():
        sys.exit(f"{src} is missing: run tools/im/extract.py on a RAM dump of your impossible_mission.d64 first")
    a = json.loads(src.read_text())
    frames = a["frames"]
    if len(frames) != 28:
        sys.exit(f"agent.json: expected 28 frames, got {len(frames)}")
    t = a["tables"]
    # the somersault ends with the deltas of frame 16 (index 0) applied when
    # the frame drops below 16: the origin moves by frame 16's offset + that
    flip_dx = frames["16"][0][2] + t["dx12"][0]
    if flip_dx != frames["16"][1][2] + t["dx3"][0]:
        sys.exit("agent.json: somersault end offset differs between the pieces")

    blk = {s: [] for s in (1, 2, 3)}
    dx = {s: [] for s in (1, 2, 3)}
    dy = {s: [] for s in (1, 2, 3)}
    for f in range(28):
        pieces = {p[0]: p for p in frames[str(f)]}
        for s in (1, 2, 3):
            if s in pieces:
                _, b, x, y = pieces[s]
                if not 0 <= b < 64 or not -128 <= x < 128 or not -128 <= y < 128:
                    sys.exit(f"agent.json: frame {f} piece {s} out of range: {pieces[s]}")
                blk[s].append(b)
                dx[s].append(x & 0xff)
                dy[s].append(y & 0xff)
            else:
                blk[s].append(0xff)
                dx[s].append(0)
                dy[s].append(0)

    def row(name, vals):
        return f"{name:<14}.byte " + ", ".join(f"${v:02x}" for v in vals) + "\n"

    out = ["; generated by tools/im/gen_mission.py from assets/im/agent.json - do not edit\n",
           f"AGENT_FLIP_DX = {flip_dx}         ; origin shift after a somersault\n",
           f"AGENT_REF_FACING = ${a['facing_flag']:02x}    ; facing of the stored blocks (byte 63)\n"]
    for s in (1, 2, 3):
        out.append(row(f"ag_blk{s}", blk[s]))
        out.append(row(f"ag_dx{s}", dx[s]))
        out.append(row(f"ag_dy{s}", dy[s]))
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("".join(out))
    print(f"mission: 28 agent frames, somersault moves {flip_dx} px")


if __name__ == "__main__":
    main()
