"""Tables for the VIPP Mission (src/mission.asm) from the extracted Impossible
Mission data in assets/im (see extract.py): writes build/mission_agent.inc.

Agent frames: per hires sprite piece (sprite 1 white overlay, 2 body, 3 legs)
the block number (0-63 within the agent sprites, $ff = piece not shown) and
its offset from the agent origin. Offsets are signed: dx is negated when the
agent faces left (as the original does with its delta tables).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
IM = ROOT / "assets" / "im"
OUT = ROOT / "build" / "mission_agent.inc"


def main():
    src = IM / "agent.json"
    if not src.exists():
        sys.exit(f"{src} is missing: run tools/im/extract.py on a RAM dump of your impossible_mission.d64 first")
    a = json.loads(src.read_text())
    frames = a["frames"]
    if len(frames) != 28:
        sys.exit(f"agent.json: expected 28 frames, got {len(frames)}")
    t = a["tables"]
    # the somersault ends with the deltas of frame 16 (index 0) applied when
    # the frame drops below 16: the origin moves by frame 16's offset + that
    flip_dx = frames["16"][0][2] + t["dx12"][0]
    if flip_dx != frames["16"][1][2] + t["dx3"][0]:
        sys.exit("agent.json: somersault end offset differs between the pieces")

    blk = {s: [] for s in (1, 2, 3)}
    dx = {s: [] for s in (1, 2, 3)}
    dy = {s: [] for s in (1, 2, 3)}
    for f in range(28):
        pieces = {p[0]: p for p in frames[str(f)]}
        for s in (1, 2, 3):
            if s in pieces:
                _, b, x, y = pieces[s]
                if not 0 <= b < 64 or not -128 <= x < 128 or not -128 <= y < 128:
                    sys.exit(f"agent.json: frame {f} piece {s} out of range: {pieces[s]}")
                blk[s].append(b)
                dx[s].append(x & 0xff)
                dy[s].append(y & 0xff)
            else:
                blk[s].append(0xff)
                dx[s].append(0)
                dy[s].append(0)

    def row(name, vals):
        return f"{name:<14}.byte " + ", ".join(f"${v:02x}" for v in vals) + "\n"

    out = ["; generated by tools/im/gen_mission.py from assets/im/agent.json - do not edit\n",
           f"AGENT_FLIP_DX = {flip_dx}         ; origin shift after a somersault\n",
           f"AGENT_REF_FACING = ${a['facing_flag']:02x}    ; facing of the stored blocks (byte 63)\n"]
    for s in (1, 2, 3):
        out.append(row(f"ag_blk{s}", blk[s]))
        out.append(row(f"ag_dx{s}", dx[s]))
        out.append(row(f"ag_dy{s}", dy[s]))
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("".join(out))
    print(f"mission: 28 agent frames, somersault moves {flip_dx} px")
    signed = lambda v: v - 256 if v > 127 else v
    agent = ([signed(v) for v in dx[3]], [signed(v) for v in dy[3]])
    room_robots = gen_rooms()
    gen_terminals()
    gen_search_find()
    gen_script(room_robots, agent)


# --- rooms ---------------------------------------------------------------------
# The rooms the agent visits, in order (built by the original, see
# extract_rooms.py; chosen by the user: rooms 0, 18, 23, 24 and 29).
ROOM_ORDER = [18, 24, 23, 29, 0]
PLATFORM = {0x45, 0x46, 0x49, 0x4a, 0x4b}
RLE = 0xff                      # $ff n v: n times v; $ff 0: end


def rle(data):
    out = []
    i = 0
    while i < len(data):
        j = i
        while j < len(data) and data[j] == data[i] and j - i < 255:
            j += 1
        n = j - i
        if n >= 3 or data[i] == RLE:
            out += [RLE, n, data[i]]
        else:
            out += [data[i]] * n
        i = j
    return out + [RLE, 0]


def unrle(data):
    out = []
    i = 0
    while True:
        if data[i] == RLE:
            if data[i + 1] == 0:
                return out
            out += [data[i + 2]] * data[i + 1]
            i += 3
        else:
            out.append(data[i])
            i += 1


def byte_rows(label, data):
    lines = [f"{label}"]
    for k in range(0, len(data), 16):
        lines.append("            .byte " + ", ".join(f"${b:02x}" for b in data[k:k + 16]))
    return "\n".join(lines) + "\n"


def robot_bounds(screen, rob):
    """Patrol bounds (sprite X) of a robot: the platform run under its feet."""
    row = (rob["y"] + 21 - 50) // 8
    col = (rob["x"] + 12 - 24) // 8          # the robot's middle
    line = screen[row * 40:row * 40 + 40]
    if not 0 <= col < 40 or line[col] not in PLATFORM:
        sys.exit(f"robot at {rob['x']},{rob['y']}: no platform under it (row {row}, column {col})")
    c0 = c1 = col
    while c0 > 0 and line[c0 - 1] in PLATFORM:
        c0 -= 1
    while c1 < 39 and line[c1 + 1] in PLATFORM:
        c1 += 1
    # the middle (x + 12) stays 4 px inside the platform ends
    return 24 + 8 * c0 + 4 - 12, 24 + 8 * (c1 + 1) - 4 - 12


def gen_rooms():
    src = IM / "rooms.json"
    if not src.exists():
        sys.exit(f"{src} is missing: run tools/im/extract_rooms.py on a room snapshot first")
    rooms = json.loads(src.read_text())
    tables = ["; generated by tools/im/gen_mission.py from assets/im/rooms.json - do not edit\n",
              f"ROOM_COUNT = {len(ROOM_ORDER)}\n"]
    data_d000, data_9000 = [], []
    budget_d000 = 0x1000
    cols = dict(bg=[], mc1=[], mc2=[], rcol=[], smc1=[], smc2=[], nrob=[])
    robots = []
    for i, n in enumerate(ROOM_ORDER):
        r = rooms[str(n)]
        if any(c < 16 for c in r["screen"]):
            sys.exit(f"room {n} uses characters 0-15 (the Searching box needs them)")
        packed = rle(r["screen"]) + rle(r["colour"])
        assert unrle(rle(r["screen"])) == r["screen"] and unrle(rle(r["colour"])) == r["colour"]
        block = byte_rows(f"room_data_{i}           ; room {n}", packed)
        if len(packed) <= budget_d000:
            data_d000.append(block)
            budget_d000 -= len(packed)
        else:
            data_9000.append(block)
        cols["bg"].append(r["bg"])
        cols["mc1"].append(r["mc1"])
        cols["mc2"].append(r["mc2"])
        cols["rcol"].append(r["robot_colours"][0])
        cols["smc1"].append(r["sprite_mc"][0])
        cols["smc2"].append(r["sprite_mc"][1])
        cols["nrob"].append(len(r["robots"]))
        if len(r["robots"]) > 4:
            sys.exit(f"room {n}: more than 4 robots")
        for k in range(4):
            if k < len(r["robots"]):
                rob = r["robots"][k]
                lo, hi = robot_bounds(r["screen"], rob)
                if not lo <= rob["x"] <= hi:
                    rob_x = min(max(rob["x"], lo), hi)
                else:
                    rob_x = rob["x"]
                robots.append((rob_x, rob["y"], lo, hi, rob["type"]))
            else:
                robots.append((0, 0, 0, 0, 0))
    tables.append("room_lo      .byte " + ", ".join(f"<room_data_{i}" for i in range(len(ROOM_ORDER))) + "\n")
    tables.append("room_hi      .byte " + ", ".join(f">room_data_{i}" for i in range(len(ROOM_ORDER))) + "\n")
    tables.append("room_number  .byte " + ", ".join(str(n) for n in ROOM_ORDER) + "   ; the original's room numbers\n")
    for k, v in cols.items():
        tables.append(f"room_{k:<7} .byte " + ", ".join(str(x) for x in v) + "\n")
    # robots: 4 per room, index room * 4 + k
    for name, idx, word in (("rob_x", 0, True), ("rob_y", 1, False), ("rob_min", 2, True), ("rob_max", 3, True),
                            ("rob_type", 4, False)):
        if word:
            tables.append(f"{name}_lo   .byte " + ", ".join(f"<{r[idx]}" for r in robots) + "\n")
            tables.append(f"{name}_hi   .byte " + ", ".join(f">{r[idx]}" for r in robots) + "\n")
        else:
            tables.append(f"{name}     .byte " + ", ".join(str(r[idx]) for r in robots) + "\n")
    (ROOT / "build" / "mission_rooms.inc").write_text("".join(tables))
    (ROOT / "build" / "mission_rooms_d000.inc").write_text("".join(data_d000) or "; (none)\n")
    (ROOT / "build" / "mission_rooms_9000.inc").write_text("".join(data_9000) or "; (none)\n")
    size = sum(len(rle(rooms[str(n)]["screen"]) + rle(rooms[str(n)]["colour"])) for n in ROOM_ORDER)
    print(f"mission: {len(ROOM_ORDER)} rooms, {size} bytes packed ({0x1000 - budget_d000} at $d000)")
    return [[r for r in robots[4 * i:4 * i + cols["nrob"][i]]] for i in range(len(ROOM_ORDER))]


# --- terminals -------------------------------------------------------------------------
def gen_terminals():
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import terminals                     # noqa: E402
    screens = terminals.screens("B")
    frame = (IM / "terminal_screen.bin").read_bytes()
    col = (IM / "terminal_colram.bin").read_bytes()
    out = ["; generated by tools/im/gen_mission.py (texts: tools/im/terminals.py) - do not edit\n",
           f"TERM_COUNT = {len(screens)}\n",
           byte_rows("term_frame          ; screen + colours, packed", rle(list(frame)) + rle(list(col)))]
    for i, scr in enumerate(screens):
        area = [scr[r * 40 + c] for r in range(3, 18) for c in range(6, 34)]
        out.append(byte_rows(f"term_text_{i}         ; rows 3-17, columns 6-33, packed", rle(area)))
    out.append("term_lo     .byte " + ", ".join(f"<term_text_{i}" for i in range(len(screens))) + "\n")
    out.append("term_hi     .byte " + ", ".join(f">term_text_{i}" for i in range(len(screens))) + "\n")
    (ROOT / "build" / "mission_term.inc").write_text("".join(out))
    (ROOT / "build" / "charset_lift_vipp.bin").write_bytes(terminals.charset())
    print(f"mission: {len(screens)} terminals")


# --- searching: what is found --------------------------------------------------------------
# The original's result box ("Nothing here.", extract_search.py): 8 x 4 room
# characters, solid ($52) where empty, the text cut out of the white in a
# small font, characters $00-$11 (the only ones the rooms leave free). The
# VIPP find is drawn the same way, in the same style (2 pixel strokes).
FIND_TEXT = ["VIPP 10", "found!"]
FIND_FONT = {
    "V": ["##..##", "##..##", "##..##", "##..##", "##..##", ".####.", "..##.."],
    "I": ["##", "##", "##", "##", "##", "##", "##"],
    "P": ["#####.", "##..##", "##..##", "#####.", "##....", "##....", "##...."],
    "1": [".##", "###", ".##", ".##", ".##", ".##", ".##"],
    "0": [".####.", "##..##", "##.###", "###.##", "##..##", "##..##", ".####."],
    "f": ["..###", ".##..", "####.", ".##..", ".##..", ".##..", ".##.."],
    "o": ["", "", ".####.", "##..##", "##..##", "##..##", ".####."],
    "u": ["", "", "##..##", "##..##", "##..##", "##..##", ".#####"],
    "n": ["", "", "#####.", "##..##", "##..##", "##..##", "##..##"],
    "d": ["....##", "....##", ".#####", "##..##", "##..##", "##..##", ".#####"],
    "!": ["##", "##", "##", "##", "##", "..", "##"],
    " ": ["...", "...", "...", "...", "...", "...", "..."],
}
FIND_LINES_Y = (9, 19)              # top pixel row of each text line (as "Nothing here.")


def gen_search_find():
    nothing = (IM / "search_nothing.bin").read_bytes()
    if len(nothing) != 32 + 18 * 8:
        sys.exit("search_nothing.bin: expected 32 layout bytes + 18 characters: run tools/im/extract_search.py")
    # 64 x 32 pixels, 1 = white (ink), the text cut out
    px = [[1] * 64 for _ in range(32)]
    for line, y0 in zip(FIND_TEXT, FIND_LINES_Y):
        glyphs = [FIND_FONT[ch] for ch in line]
        widths = [max(len(row) for row in g) for g in glyphs]
        width = sum(w + 1 for w in widths) - 1
        x = (64 - width) // 2
        for g, w in zip(glyphs, widths):
            for r, row in enumerate(g):
                for k, c in enumerate(row):
                    if c == "#":
                        px[y0 + r][x + k] = 0
            x += w + 1
    layout, chars = [], []
    for cr in range(4):
        for cc in range(8):
            cell = bytes(sum(px[cr * 8 + y][cc * 8 + b] << (7 - b) for b in range(8)) for y in range(8))
            if cell == b"\xff" * 8:
                layout.append(0x52)
            else:
                if cell not in chars:
                    chars.append(cell)
                layout.append(chars.index(cell))
    if len(chars) > 18:
        sys.exit(f"search find box needs {len(chars)} characters, only $00-$11 are free")
    out = bytes(layout) + b"".join(chars) + bytes(8 * (18 - len(chars)))
    (ROOT / "build" / "search_find.bin").write_bytes(out)
    print(f"mission: search find box '{' / '.join(FIND_TEXT)}' ({len(chars)} characters)")


# --- the script ------------------------------------------------------------------------
def gen_script(room_robots, agent):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import mission_script                 # noqa: E402
    (ROOT / "build" / "mission_script.inc").write_text(mission_script.emit())
    deaths = mission_script.check(room_robots, agent)
    if len(deaths) != mission_script.PLANNED_DEATHS:
        mission_script.check(room_robots, agent, verbose=True)
        sys.exit(f"mission script: {len(deaths)} deaths in a loop, planned {mission_script.PLANNED_DEATHS}: "
                 + "; ".join(f"room index {d[0]} tick {d[1]} x {d[2]} ({d[3]})" for d in deaths))
    print(f"mission: script ok ({len(deaths)} planned death per loop)")


if __name__ == "__main__":
    main()
