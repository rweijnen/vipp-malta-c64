def _parse():
    glyphs = {" ": ["......."] * 7}
    lines = _SRC.strip().splitlines()
    i = 0
    while i < len(lines):
        ch, rows = lines[i], lines[i + 1:i + 8]
        if len(ch) != 1 or len(rows) != 7 or any(len(r) != 7 for r in rows):
            raise ValueError(f"bad glyph definition for {ch!r}")
        glyphs[ch] = rows
        i += 8
    return glyphs


GLYPHS = _parse()
