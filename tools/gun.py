MUZZLE_ROW = 7      # beam leaves the gun on this sprite row


def parse(src):
    rows = src.strip("\n").splitlines()
    if len(rows) != 21 or any(len(r) != 12 for r in rows):
        raise ValueError(f"gun sprite must be 21 rows of 12, got {[len(r) for r in rows]}")
    return rows
